#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

import { skillManifest } from '../src/scripts/workflows/skill-manifest.ts';
import { VERSION } from '../src/scripts/lib/version.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function parseArgs(argv: string[]): Record<string, string | boolean | string[]> {
  const args: Record<string, string | boolean | string[]> = { _: [] as string[] };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];

    if (arg.startsWith('--')) {
      if (arg.includes('=')) {
        const idx = arg.indexOf('=');
        const key = arg.slice(2, idx);
        const value = arg.slice(idx + 1);
        args[key] = value;
        continue;
      }

      const key = arg.slice(2);
      const next = argv[i + 1];

      if (next === undefined || next.startsWith('--')) {
        args[key] = true;
      } else {
        args[key] = next;
        i += 1;
      }
    } else {
      (args._ as string[]).push(arg);
    }
  }

  return args;
}

function fail(message: string) {
  console.error(`[deploy-to-agent] ${message}`);
  process.exit(1);
}

function ensureDir(dir: string) {
  fs.mkdirSync(dir, { recursive: true });
}

function rmrf(target: string) {
  fs.rmSync(target, { recursive: true, force: true });
}

function copyDir(src: string, dest: string) {
  if (!fs.existsSync(src)) {
    fail(`Missing source directory: ${src}`);
  }

  ensureDir(path.dirname(dest));
  fs.cpSync(src, dest, { recursive: true });
}

function indent(text: string, spaces: number) {
  const pad = ' '.repeat(spaces);

  return String(text || '')
    .split('\n')
    .map((line) => (line.trim() === '' ? '' : `${pad}${line}`))
    .join('\n');
}

const SKILL_TEMPLATE = [
  '---',
  'name: {{ID}}',
  'description: |',
  '{{DESCRIPTION_INDENTED}}',
  '---',
  '',
  '# {{TITLE}}',
  '',
  'Generated by agentic-sdlc. Do not edit manually.',
  '',
  '## Workflow',
  '',
  '1. Run `node scripts/sdlc.js status --dir <change_dir>` (or `node scripts/sdlc.js --list-workflows`, `--help`).',
  '2. Follow the `instructions` field in the returned envelope `{workflow, step, state, instructions, data, errors, warnings}`.',
  '3. The CLI owns stage detection — do not guess which workflow to run.',
  '',
  'Workflows: requirements · design · planning · implementation · review · feedback · knowledge-extraction',
  '',
].join('\n');

function renderSkill() {
  return SKILL_TEMPLATE.replaceAll('{{ID}}', skillManifest.id)
    .replaceAll('{{TITLE}}', skillManifest.title)
    .replaceAll('{{DESCRIPTION_INDENTED}}', indent(skillManifest.description, 2));
}

const LEGACY_SKILL_IDS = [
  'requirements-authoring',
  'design-authoring',
  'planning',
  'implementation',
  'review',
  'feedback',
  'knowledge-extraction',
];

function main() {
  const args = parseArgs(process.argv.slice(2));

  const destArg = args.dest || (args._ as string[])[0];

  if (!destArg) {
    fail(
      'Usage: deploy-to-agent --dest <agent-root> ' +
      '[--clean] [--skip-smoke]'
    );
  }

  const destAbs = path.resolve(String(destArg));
  const skillAbs = path.join(destAbs, 'skills', 'agentic-sdlc');

  if (args.clean) {
    rmrf(skillAbs);

    // Remove legacy split layout (pre-consolidation): old runtime dir + per-skill dirs
    rmrf(path.join(destAbs, 'sdlc'));
    for (const skillId of LEGACY_SKILL_IDS) {
      rmrf(path.join(destAbs, 'skills', skillId));
    }
  }

  ensureDir(path.join(skillAbs, 'scripts'));

  const buildResult = spawnSync('npm', ['run', 'build'], {
    cwd: root,
    encoding: 'utf8',
    shell: true,
  });

  if (buildResult.status !== 0) {
    if (buildResult.stdout) process.stderr.write(buildResult.stdout);
    if (buildResult.stderr) process.stderr.write(buildResult.stderr);
    fail('Runtime build failed.');
  }

  const bundleFile = path.join(root, 'dist', 'sdlc.js');

  if (!fs.existsSync(bundleFile)) {
    fail(`Missing bundle file: ${bundleFile}`);
  }

  fs.copyFileSync(bundleFile, path.join(skillAbs, 'scripts', 'sdlc.js'));

  copyDir(path.join(root, 'src', 'templates'), path.join(skillAbs, 'templates'));
  copyDir(path.join(root, 'src', 'schemas'), path.join(skillAbs, 'schemas'));
  copyDir(path.join(root, 'src', 'policies'), path.join(skillAbs, 'policies'));

  fs.writeFileSync(
    path.join(skillAbs, 'SKILL.md'),
    `${renderSkill()}\n`,
    'utf8'
  );

  fs.writeFileSync(
    path.join(skillAbs, 'manifest.json'),
    `${JSON.stringify(
      {
        name: skillManifest.id,
        version: VERSION,
        deployedAt: new Date().toISOString(),
        cliPath: 'scripts/sdlc.js',
      },
      null,
      2
    )}\n`,
    'utf8'
  );

  let smoke = 'skipped';

  if (!args['skip-smoke']) {
    const runtimeCliAbs = path.join(skillAbs, 'scripts', 'sdlc.js');
    const result = spawnSync(
      process.execPath,
      [runtimeCliAbs, '--list-workflows'],
      {
        cwd: destAbs,
        encoding: 'utf8',
      }
    );

    if (result.status !== 0) {
      fail(
        `Deployment smoke test failed.\n${result.stdout || ''}\n${result.stderr || ''}`
      );
    }

    smoke = 'passed';
  }

  console.log(
    JSON.stringify(
      {
        ok: true,
        version: VERSION,
        dest: destAbs,
        skill: skillAbs,
        cliPath: 'scripts/sdlc.js',
        bundled: true,
        smoke,
      },
      null,
      2
    )
  );
}

main();
